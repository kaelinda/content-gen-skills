#!/usr/bin/env python3
"""Bootstrap this checkout with Python 3.11+ and the standard library only.

The default project target never installs a user-level Skill. Explicit agent
selection creates only a small pointer to this checkout, never copies its rules
or credentials. Native Windows is unsupported; use WSL for the Unix pipeline.
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass
import json
import os
from pathlib import Path
import shlex
import stat
import subprocess
import sys


SKILL_NAME = "publishing-wechat-articles"
PROBE = (
    "import json,sys,sysconfig; print(json.dumps({'version': list(sys.version_info[:2]), "
    "'prefix': sys.prefix, 'base_prefix': sys.base_prefix, 'paths': sysconfig.get_paths()}))"
)


class BootstrapError(Exception):
    """A safe, actionable bootstrap failure, without subprocess output."""


@dataclass(frozen=True)
class Plan:
    root: Path
    agent: str
    bridge: Path | None
    bridge_text: str
    skip_deps: bool
    skip_browser: bool

    @property
    def venv(self) -> Path:
        return self.root / ".venv"

    @property
    def python(self) -> Path:
        # Do not resolve this symlink: doing so would bypass the virtualenv.
        return self.venv / "bin" / "python"

    @property
    def preflight(self) -> list[str]:
        return [str(self.python), str(self.root / SKILL_NAME / "scripts" / "pipeline.py"),
                "--workspace", str(self.root / "output"),
                "preflight", "--mode", "prepare-only", "--json"]


def parser() -> argparse.ArgumentParser:
    result = argparse.ArgumentParser(description=__doc__)
    result.add_argument("--agent", choices=("project", "hermes", "codex", "claude", "generic"),
                        default="project", help="default: check project discovery links only")
    result.add_argument("--skills-dir", type=Path,
                        help="explicit Skill parent directory; appends publishing-wechat-articles; "
                             "requires a non-project agent (mandatory for generic)")
    result.add_argument("--dry-run", action="store_true",
                        help="validate and print the plan; no writes, installs, or subprocesses")
    result.add_argument("--skip-deps", action="store_true",
                        help="skip pip install, but still create/check .venv and run preflight")
    result.add_argument("--skip-browser", action="store_true",
                        help="skip Chromium installation, not its prepare-only preflight check")
    return result


def metadata(path: Path) -> os.stat_result | None:
    try:
        return path.lstat()
    except FileNotFoundError:
        return None


def plain_file(path: Path, *, single_link: bool = False) -> bool:
    info = metadata(path)
    if info is None:
        return False
    if not stat.S_ISREG(info.st_mode) or (single_link and info.st_nlink != 1):
        raise BootstrapError(f"Conflict: expected a regular, non-symlink file at {path}")
    return True


def directory_chain(path: Path) -> None:
    """Reject redirected or non-directory targets before any side effects."""
    for parent in reversed((path, *path.parents)):
        info = metadata(parent)
        if info is not None and not stat.S_ISDIR(info.st_mode):
            raise BootstrapError(f"Conflict: directory is a symlink or not a directory: {parent}")


def read_plain(path: Path) -> bytes:
    # O_NONBLOCK avoids hanging if a regular file is replaced by a FIFO.
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(fd, "rb") as stream:
        if not stat.S_ISREG(os.fstat(stream.fileno()).st_mode):
            raise BootstrapError(f"Conflict: expected a regular file at {path}")
        return stream.read()


def bridge_text(root: Path) -> str:
    canonical = root / SKILL_NAME
    python = root / ".venv" / "bin" / "python"
    cli = canonical / "scripts" / "pipeline.py"
    command = shlex.join([str(python), str(cli), "--workspace", str(root / "output"),
                          "preflight", "--mode", "prepare-only", "--json"])
    return f"""---
name: {SKILL_NAME}
description: Use when collecting, writing, preparing, or publishing Chinese WeChat articles with this local repository.
---

# Repository bridge (generated by scripts/bootstrap.py)

This file is a pointer, not a copy of the business Skill.
Before doing any work, read the canonical Skill and follow its linked contracts:

```text
{canonical / 'SKILL.md'}
```

Resolve every relative reference in that Skill against its canonical directory,
not this bridge directory. The only source of truth is the current checkout:

```text
Repository: {root}
Canonical Skill directory: {canonical}
Virtualenv Python: {python}
Pipeline CLI: {cli}
```

Run from the repository root, always using the virtualenv Python above:

```sh
cd {shlex.quote(str(root))}
{command}
```

The canonical Skill supplies all workflow and authorization rules. Never execute
legacy vendor scripts. This bridge grants no publishing or paid-generation
permission. Never copy or print `.env` or `config/runtime.local.toml`; credentials
stay in the checkout/environment. Follow the canonical configuration contract.
If the checkout moves, review and remove this bridge yourself, then rerun
bootstrap for the new path. Bootstrap will not overwrite a different bridge.
"""


def check_bridge(path: Path, expected: str) -> bool:
    directory_chain(path.parent)
    if plain_file(path):
        if read_plain(path) != expected.encode("utf-8"):
            raise BootstrapError(
                f"Conflict: existing bridge differs: {path}. The checkout may have moved. "
                "Review and remove it yourself, or choose another --skills-dir; nothing is overwritten."
            )
        return True
    if path.parent.exists() and any(path.parent.iterdir()):
        raise BootstrapError(f"Conflict: existing non-empty Skill directory has no matching SKILL.md: {path.parent}")
    return False


def check_venv(plan: Plan) -> bool:
    info = metadata(plan.venv)
    if info is None:
        return False
    directory_chain(plan.venv / "bin")
    if not plain_file(plan.venv / "pyvenv.cfg") or not plan.python.is_file() or not os.access(plan.python, os.X_OK):
        raise BootstrapError(
            f"Conflict: incomplete or invalid virtualenv at {plan.venv}; "
            "review and remove/recreate it yourself."
        )
    return True


def make_plan(args: argparse.Namespace, root: Path) -> Plan:
    root = root.resolve(strict=True)
    if not root.is_dir():
        raise BootstrapError(f"Not a repository directory: {root}")
    canonical = root / SKILL_NAME
    directory_chain(canonical / "scripts")
    for path in (canonical / "SKILL.md", canonical / "scripts" / "pipeline.py", root / "requirements.txt"):
        if not plain_file(path):
            raise BootstrapError(f"Required repository file is missing: {path}")
    if args.agent == "project" and args.skills_dir is not None:
        raise BootstrapError("--skills-dir requires --agent generic, hermes, codex, or claude; project is local-only.")
    if args.agent == "generic" and args.skills_dir is None:
        raise BootstrapError("--agent generic requires --skills-dir (a parent directory).")

    bridge = None
    if args.agent == "project":
        # These are repository-owned relative links. Never recreate or replace them.
        for relative in (".agents/skills", ".claude/skills"):
            entry = root / relative / SKILL_NAME
            if not entry.is_symlink() or entry.resolve() != canonical:
                raise BootstrapError(f"Conflict: project discovery must be an existing symlink to {canonical}: {entry}")
        for name in ("AGENTS.md", "CLAUDE.md"):
            if not plain_file(root / name):
                raise BootstrapError(f"Required project instructions are missing: {root / name}")
    else:
        if args.skills_dir is not None:
            base = args.skills_dir
        elif args.agent == "hermes":
            home = os.environ.get("HERMES_HOME")
            base = (Path(home).expanduser() if home else Path.home() / ".hermes") / "skills"
        elif args.agent == "codex":
            base = Path.home() / ".agents" / "skills"
        else:
            base = Path.home() / ".claude" / "skills"
        # Keep symlinks visible to conflict checks instead of resolving through them.
        base = Path(os.path.abspath(base.expanduser()))
        bridge = base / SKILL_NAME / "SKILL.md"

    plan = Plan(root, args.agent, bridge, bridge_text(root), args.skip_deps, args.skip_browser)
    if bridge is not None:
        check_bridge(bridge, plan.bridge_text)
    check_venv(plan)
    if not plain_file(root / ".env", single_link=True) and not plain_file(root / ".env.example"):
        raise BootstrapError(f"Required template is missing: {root / '.env.example'}")
    return plan


def child_environment() -> dict[str, str]:
    env = os.environ.copy()
    # Keep injected application credentials private; never source or parse .env.
    # Ignore interpreter/scheme overrides, alternate install/build destinations,
    # and inherited log/report files. Keep intentional index/proxy/TLS settings.
    for key in ("PYTHONHOME", "PYTHONPATH", "PYTHONUSERBASE", "PYTHONPLATLIBDIR",
                "PYTHONEXECUTABLE", "__PYVENV_LAUNCHER__", "_PYTHON_PROJECT_BASE",
                "_PYTHON_SYSCONFIGDATA_NAME", "_PYTHON_SYSCONFIGDATA_PATH",
                "PIP_TARGET", "PIP_PREFIX", "PIP_PYTHON", "PIP_ROOT", "PIP_SRC",
                "PIP_BUILD", "PIP_BUILD_TRACKER", "PIP_INSTALL_OPTION", "PIP_GLOBAL_OPTION",
                "PIP_BUILD_OPTION", "PIP_CONFIG_SETTINGS", "PIP_LOG", "PIP_REPORT"):
        env.pop(key, None)
    env.update(PYTHONDONTWRITEBYTECODE="1", PIP_REQUIRE_VIRTUALENV="true", PIP_USER="0",
               PIP_CONFIG_FILE=os.devnull, PIP_DISABLE_PIP_VERSION_CHECK="1", PIP_NO_CACHE_DIR="1")
    return env


def run(plan: Plan, command: list[str], label: str, *, allow_failure: bool = False) -> subprocess.CompletedProcess[str]:
    print(f"{label}: {shlex.join(command)}", flush=True)
    result = subprocess.run(command, cwd=plan.root, env=child_environment(),
                            capture_output=True, text=True, encoding="utf-8", errors="replace", check=False)
    if result.returncode and not allow_failure:
        raise BootstrapError(
            f"{label} failed (exit {result.returncode}); stopped. "
            "Output withheld to avoid exposing credentials; rerun the displayed command locally for diagnostics."
        )
    return result


def verify_python(plan: Plan) -> None:
    result = run(plan, [str(plan.python), "-c", PROBE], "Check virtualenv Python")
    try:
        info = json.loads(result.stdout)
        valid = (info["version"] >= [3, 11]
                 and Path(info["prefix"]).resolve() == plan.venv
                 and info["prefix"] != info["base_prefix"])
        # sys.prefix alone misses symlinked site-packages or library ancestors.
        # Check installation destinations, not stdlib/include: a valid venv can
        # legitimately use those read-only paths from its base interpreter.
        if valid:
            for key in ("purelib", "platlib", "scripts", "data"):
                path = Path(info["paths"][key])
                if (not path.is_absolute() or not path.resolve().is_relative_to(plan.venv)
                        or (path.exists() and not path.is_dir())):
                    valid = False
                    break
    except (ValueError, TypeError, KeyError, OSError, RuntimeError):
        valid = False
    if not valid:
        raise BootstrapError(
            f"Invalid virtualenv Python: expected Python 3.11+ and installation paths isolated at {plan.venv}; "
            "recreate it yourself."
        )


def create_exclusive(path: Path, content: bytes, mode: int) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, mode)
    with os.fdopen(fd, "wb") as stream:
        os.fchmod(stream.fileno(), mode)
        stream.write(content)


def ensure_env(root: Path) -> None:
    path = root / ".env"
    if not plain_file(path, single_link=True):
        try:
            create_exclusive(path, read_plain(root / ".env.example"), 0o600)
            print(f"Created {path} from .env.example (0600); values not printed.")
            return
        except FileExistsError:
            # A concurrent creator is never overwritten.
            pass
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(fd, "rb") as stream:
        info = os.fstat(stream.fileno())
        if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
            raise BootstrapError(f"Conflict: .env must be a regular file with one link: {path}")
        os.fchmod(stream.fileno(), 0o600)
    print(f"Preserved {path} contents; permissions set to 0600. Values not printed.")


def install_bridge(plan: Plan) -> None:
    if plan.bridge is None:
        print("Project discovery links verified and preserved; no user-level Skill was installed.")
        return
    existed = check_bridge(plan.bridge, plan.bridge_text)
    if not existed:
        plan.bridge.parent.mkdir(parents=True, exist_ok=True)
        check_bridge(plan.bridge, plan.bridge_text)
        try:
            create_exclusive(plan.bridge, plan.bridge_text.encode("utf-8"), 0o644)
        except FileExistsError:
            # Only an identical concurrently installed bridge is acceptable.
            pass
    if not check_bridge(plan.bridge, plan.bridge_text):
        raise BootstrapError(f"Bridge verification failed: {plan.bridge}")
    print(f"{'Reused' if existed else 'Installed and verified'} bridge: {plan.bridge}")


def preflight(plan: Plan) -> None:
    result = run(plan, plan.preflight, "Prepare-only preflight", allow_failure=True)
    try:
        report = json.loads(result.stdout)
    except (ValueError, TypeError):
        report = None
    if not (isinstance(report, dict) and report.get("mode") == "prepare-only"
            and type(report.get("ready")) is bool
            and isinstance(report.get("checks"), list)
            and isinstance(report.get("failures"), list)):
        raise BootstrapError(
            f"Preflight failed (exit {result.returncode}): no valid prepare-only JSON report. "
            "Raw output withheld to avoid exposing credentials; no readiness is claimed."
        )
    if report["ready"] and (result.returncode or report["failures"]):
        raise BootstrapError("Preflight returned an inconsistent success report; no readiness is claimed.")
    # Normal preflight reports contain dependency checks, never runtime credentials.
    print(json.dumps(report, ensure_ascii=False, indent=2))
    if result.returncode or not report["ready"]:
        raise BootstrapError(f"Prepare-only preflight did not pass (exit {result.returncode}); bootstrap is not ready.")


def execute(plan: Plan, *, dry_run: bool) -> None:
    create_venv = not check_venv(plan)
    venv_command = [sys.executable, "-m", "venv", str(plan.venv)]
    pip_command = [str(plan.python), "-m", "pip", "install", "-r", str(plan.root / "requirements.txt")]
    browser_command = [str(plan.python), "-m", "playwright", "install", "chromium"]
    if dry_run:
        print("DRY RUN: no files, permissions, installs, or subprocesses will be changed/run.")
        print(f"Repository: {plan.root}\nAgent: {plan.agent}")
        print(f"Virtualenv: {'create' if create_venv else 'reuse'} {plan.venv}")
        if create_venv:
            print(shlex.join(venv_command))
        print(shlex.join([str(plan.python), "-c", PROBE]))
        print("Dependencies: skipped" if plan.skip_deps else shlex.join(pip_command))
        print("Chromium install: skipped" if plan.skip_browser else shlex.join(browser_command))
        print(f".env: {'preserve contents and chmod' if (plan.root / '.env').exists() else 'create from .env.example with mode'} 0600")
        print(shlex.join(plan.preflight))
        print(f"Bridge: verify/create {plan.bridge}" if plan.bridge else "Project discovery links: preserve; no user-level writes")
        print("Preflight NOT RUN; readiness is unknown. No credentials were loaded.")
        return
    if create_venv:
        run(plan, venv_command, "Create virtualenv")
    if not check_venv(plan):
        raise BootstrapError(f"Virtualenv was not created: {plan.venv}")
    verify_python(plan)
    if not plan.skip_deps:
        run(plan, pip_command, "Install Python dependencies")
    if not plan.skip_browser:
        run(plan, browser_command, "Install Chromium")
    ensure_env(plan.root)
    preflight(plan)
    install_bridge(plan)
    print("Bootstrap complete: prepare-only preflight passed. Publishing credentials, remote permissions, "
          "and login state have NOT been verified.")


def main(argv: list[str] | None = None, *, repo_root: Path | None = None) -> int:
    args = parser().parse_args(argv)
    try:
        if sys.version_info < (3, 11):
            raise BootstrapError("Python 3.11+ is required; rerun with a supported interpreter.")
        if os.name == "nt":
            raise BootstrapError("Native Windows is unsupported: use WSL (the pipeline requires fcntl/Unix file locks).")
        root = repo_root if repo_root is not None else Path(__file__).resolve().parents[1]
        plan = make_plan(args, root)
        execute(plan, dry_run=args.dry_run)
        return 0
    except (BootstrapError, OSError, subprocess.SubprocessError) as exc:
        # Never forward raw subprocess stdout/stderr, which may contain credentials.
        message = str(exc) if not isinstance(exc, subprocess.SubprocessError) else "Subprocess failed; bootstrap stopped."
        print(f"bootstrap: {message}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
